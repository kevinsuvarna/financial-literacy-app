import { Howl, Howler } from 'howler';
import { volumeFor } from './loudness';

/**
 * How loud each kind of sound should be, in dBFS while it sounds. Feedback on an answer is the
 * loudest thing in the game, and "wrong" is exactly as loud as "correct"; story events sit a
 * step below; clicks and keys below that; and the typewriter's tick — many a second while a
 * line types out — is a texture, well under everything else.
 */
export const LOUDNESS_TIERS = {
  feedback: -18,
  event: -21,
  ui: -24,
  texture: -30,
} as const;

export type LoudnessTier = keyof typeof LOUDNESS_TIERS;

/**
 * Every sound effect in the game. Each is a file in public/audio — placeholders generated by
 * scripts/generate-placeholder-audio.mjs until real sound design replaces them.
 *
 * `loudness` is what the file measures (see loudness.ts). The volume it is played at is worked
 * out from that and its tier, so every sound lands at its tier's level. A test re-measures the
 * files: replace one, and the test says what to write here.
 */
export const SOUNDS = {
  click: { file: 'click.wav', tier: 'ui', loudness: -18.1 },
  ring: { file: 'ring.wav', tier: 'event', loudness: -11.7 },
  answer: { file: 'answer.wav', tier: 'event', loudness: -14.0 },
  type: { file: 'type.wav', tier: 'texture', loudness: -27.6 },
  static: { file: 'static.wav', tier: 'event', loudness: -14.2 },
  scan: { file: 'scan.wav', tier: 'event', loudness: -13.5 },
  correct: { file: 'correct.wav', tier: 'feedback', loudness: -12.6 },
  wrong: { file: 'wrong.wav', tier: 'feedback', loudness: -17.9 },
  'level-complete': { file: 'level-complete.wav', tier: 'feedback', loudness: -11.3 },
  squeak: { file: 'squeak.wav', tier: 'ui', loudness: -20.5 },
  thud: { file: 'thud.wav', tier: 'event', loudness: -11.4 },
  ping: { file: 'ping.wav', tier: 'event', loudness: -14.0 },
  drain: { file: 'drain.wav', tier: 'event', loudness: -15.7 },
  reveal: { file: 'reveal.wav', tier: 'feedback', loudness: -16.7 },
  key: { file: 'key.wav', tier: 'ui', loudness: -15.3 },
  boot: { file: 'boot.wav', tier: 'event', loudness: -17.0 },
  unlock: { file: 'unlock.wav', tier: 'feedback', loudness: -14.2 },
  paperclip: { file: 'paperclip.wav', tier: 'ui', loudness: -20.1 },
} as const satisfies Record<string, { file: string; tier: LoudnessTier; loudness: number }>;

export type SoundName = keyof typeof SOUNDS;

/** The volume a sound is played at, to bring it to its tier's level. */
export function soundVolume(name: SoundName): number {
  const { tier, loudness } = SOUNDS[name];
  return volumeFor(loudness, LOUDNESS_TIERS[tier]);
}

/** The same sound asked for again within this window is dropped rather than stacked. */
const REPEAT_GUARD_MS = 60;
const MUTE_KEY = 'ssa-muted';

const howls = new Map<SoundName, Howl>();
const lastPlayedAt = new Map<SoundName, number>();

function getHowl(name: SoundName): Howl {
  let howl = howls.get(name);
  if (!howl) {
    howl = new Howl({
      src: [`${import.meta.env.BASE_URL}audio/${SOUNDS[name].file}`],
      volume: soundVolume(name),
    });
    howls.set(name, howl);
  }
  return howl;
}

// Sound is decoration: nothing here may throw into game code, so every entry point swallows
// errors (a blocked autoplay, a missing file, a browser without Web Audio).

export function playSound(name: SoundName, { delayMs = 0 }: { delayMs?: number } = {}): void {
  const play = () => {
    try {
      const now = performance.now();
      if (now - (lastPlayedAt.get(name) ?? -Infinity) < REPEAT_GUARD_MS) return;
      lastPlayedAt.set(name, now);
      getHowl(name).play();
    } catch {
      // See above.
    }
  };
  if (delayMs > 0) setTimeout(play, delayMs);
  else play();
}

/** Starts a sound looping and returns the function that stops it. */
export function loopSound(name: SoundName): () => void {
  try {
    const howl = getHowl(name);
    const id = howl.play();
    howl.loop(true, id);
    return () => howl.stop(id);
  } catch {
    return () => {};
  }
}

/**
 * Call from a click/tap handler. Browsers keep audio suspended until the player interacts with
 * the page; this resumes it and loads every sound, so the first effect isn't late or silent.
 */
export function unlockAudio(): void {
  try {
    for (const name of Object.keys(SOUNDS) as SoundName[]) getHowl(name);
    // `ctx` is typed as always present but is null where Web Audio is unavailable.
    const context: AudioContext | null = Howler.ctx;
    if (context?.state === 'suspended') void context.resume();
  } catch {
    // See above.
  }
}

// --- Mute -------------------------------------------------------------------------------

const muteListeners = new Set<() => void>();

function readMuted(): boolean {
  try {
    return window.localStorage.getItem(MUTE_KEY) === '1';
  } catch {
    return false;
  }
}

let muted = readMuted();
Howler.mute(muted);

export function isMuted(): boolean {
  return muted;
}

export function setMuted(next: boolean): void {
  if (next === muted) return;
  muted = next;
  Howler.mute(muted);
  try {
    window.localStorage.setItem(MUTE_KEY, muted ? '1' : '0');
  } catch {
    // Storage disabled: the setting lasts for this page load.
  }
  for (const listener of muteListeners) listener();
}

export function subscribeToMuted(listener: () => void): () => void {
  muteListeners.add(listener);
  return () => muteListeners.delete(listener);
}
